export function I18nProvider({ children }) {
  const [lang, setLangState] = useState('th');

  // Thai is always the default. A language picked by the user is remembered only for the
  // current browser tab session (sessionStorage), so every new visit opens in Thai.
  useEffect(() => {
    try {
      localStorage.removeItem('lang'); // drop the old permanent setting
      const l = sessionStorage.getItem('lang');
      if (l && DICT[l]) setLangState(l);
    } catch {}
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l) => {
    setLangState(l);
    try {
      sessionStorage.setItem('lang', l);
    } catch {}
  }, []);

  const t = useCallback(
    (k, vars) => {
      let s = DICT[lang][k] ?? DICT.en[k] ?? k;
      if (vars) for (const [a, b] of Object.entries(vars)) s = s.replaceAll(`{${a}}`, String(b));
      return s;
    },
    [lang]
  );

  const value = useMemo(() => ({ lang, setLang, t, locale: lang === 'th' ? 'th-TH' : 'en-GB' }), [lang, setLang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
